import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base = process.env.SCOTTY_TEST_URL;
assert.ok(base, 'Set SCOTTY_TEST_URL to an isolated demo server');
const browser = await chromium.launch();
try {
  const context = await browser.newContext();
  const page = await context.newPage();
  page.setDefaultTimeout(7000);
  const settings = () => page.getByRole('button', { name: 'Settings', exact: true }).click();
  const toggle = page.getByRole('switch', { name: 'Use Focus as the default view' });
  await page.goto(`${base}/p/demo`);
  await settings();
  assert.equal(await toggle.getAttribute('aria-checked'), 'false');
  await toggle.click();
  assert.equal(await toggle.getAttribute('aria-checked'), 'true');
  await page.getByRole('heading', { name: 'Settings', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Focus', exact: true }).waitFor();
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: 'Focus', exact: true }).waitFor();
  await settings();
  assert.equal(await toggle.getAttribute('aria-checked'), 'true');
  await toggle.click();
  await page.reload();
  await page.locator('article').first().waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Focus', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Focus', exact: true }).click();
  await page.reload();
  await page.locator('article').first().waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Focus', exact: true }).count(), 0, 'Choosing Focus alone does not opt in');
  await settings();
  await toggle.click();
  const other = await browser.newContext();
  const otherPage = await other.newPage();
  await otherPage.goto(`${base}/p/demo`);
  await otherPage.getByRole('button', { name: 'Settings', exact: true }).click();
  assert.equal(await otherPage.getByRole('switch', { name: 'Use Focus as the default view' }).getAttribute('aria-checked'), 'false');
  await page.screenshot({ path: '/tmp/scotty-default-view-setting.png' });
  console.log('PASS: off by default, explicit opt-in, reload landing, manual navigation, saved setting, and browser isolation');
} finally { await browser.close(); }
